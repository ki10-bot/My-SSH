                Write-InstallLog "Passwort setzen fehlgeschlagen: $_" "ERROR"
                Write-Host "FEHLER: Passwort konnte nicht gesetzt werden: $_" -ForegroundColor Red
            }
        }
    }

    # Clear plain password from memory ASAP
    try { $GeneratedConfig.WindowsPassword = $null; $secPw = $null } catch {}

