            # Fallback to net user (older systems)
            try {
                # Use net user with plain password — avoid logging
                $netArgs = "user `"$($GeneratedConfig.WindowsUser)`" `"$($GeneratedConfig.WindowsPassword)`""
                # We must NOT log password, so run via Start-Process with hidden args
                $psi = New-Object System.Diagnostics.ProcessStartInfo
                $psi.FileName = "net.exe"
                $psi.Arguments = $netArgs
                $psi.UseShellExecute = $false
                $psi.CreateNoWindow = $true
                $psi.RedirectStandardOutput = $true
                $psi.RedirectStandardError = $true
                $p = [System.Diagnostics.Process]::Start($psi)
                $p.WaitForExit()
                if ($p.ExitCode -eq 0) {
                    Write-InstallLog "Passwort via net user gesetzt."
                    Write-Host "  Passwort gesetzt (net user)." -ForegroundColor Green
                } else {
                    throw "net user exit $($p.ExitCode): $($p.StandardError.ReadToEnd())"
                }
