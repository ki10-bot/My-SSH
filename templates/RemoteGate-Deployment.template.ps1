    function Set-Directive { param([string]$FileContent,[string]$Directive,[string]$Value)
        $pattern = "(?m)^\s*#?\s*$Directive\s+.*$"
        if ($FileContent -match $pattern) { return [regex]::Replace($FileContent,$pattern,"$Directive $Value") }
        else { return $FileContent.TrimEnd() + "`r`n$Directive $Value`r`n" }
    }
    $content = Set-Directive $content "PubkeyAuthentication" "yes"
    $content = Set-Directive $content "PermitEmptyPasswords" "no"
    $content = Set-Directive $content "PermitRootLogin" "no"
    $content = Set-Directive $content "X11Forwarding" "no"
    $content = Set-Directive $content "AllowTcpForwarding" "yes"
    $content = Set-Directive $content "GatewayPorts" "no"
    $content = Set-Directive $content "ChallengeResponseAuthentication" "no"
    $content = Set-Directive $content "StrictModes" "yes"
    $content = Set-Directive $content "MaxAuthTries" "3"
    $content = Set-Directive $content "LoginGraceTime" "60"
    $content = Set-Directive $content "ClientAliveInterval" "30"
    $content = Set-Directive $content "ClientAliveCountMax" "3"
