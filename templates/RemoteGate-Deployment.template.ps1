    - This template contains ONLY placeholders (DEIN_PASSWORT) — never a real password.
    - The generated final script is PRIVATE to your Yandex bucket — never commit it to GitHub.
    - PasswordAuthentication is OFF by default; only enabled if you set a password in the wizard.

